import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const directory = dirname(fileURLToPath(import.meta.url));
const defaultOutputPath = resolve(directory, "arcturus_labels.js");
const [sourceArg, outputArg] = process.argv.slice(2);

if (!sourceArg) {
  console.error(
    "Usage: node generate_arcturus_labels.mjs SOURCE_PATH [OUTPUT_PATH]"
  );
  process.exit(2);
}

const sourcePath = resolve(sourceArg);
const outputPath = outputArg ? resolve(outputArg) : defaultOutputPath;
const greekAliases = {
  alp: "alpha",
  bet: "beta",
  gam: "gamma",
  del: "delta",
  eps: "epsilon"
};

function normalizeLabel(rawLabel) {
  const trimmed = rawLabel.trim().replace(/\s+/g, " ");
  const hydrogenPattern = /^(.+?)\$_\{([^}]+)\}\$$/;
  const match = trimmed.match(hydrogenPattern);
  if (!match) {
    return trimmed;
  }

  const prefix = match[1].trim();
  const parts = match[2].trim().split("-");
  if (parts.length === 1) {
    return `${prefix} ${parts[0]}`.replace(/\s+/g, " ");
  }

  const series = parts[0];
  const suffix = greekAliases[parts[1]] || parts[1];
  return `${prefix} ${series}-${suffix}`.replace(/\s+/g, " ");
}

function parseAtlasLine(line, lineNumber) {
  const trimmed = line.trim();
  if (!trimmed) {
    return null;
  }

  const match = trimmed.match(/^([+-]?\d+(?:\.\d+)?)\s*;\s*(.+)$/);
  if (!match) {
    throw new Error(`Unable to parse line ${lineNumber}: ${line}`);
  }

  return {
    x: Number.parseFloat(match[1]),
    text: normalizeLabel(match[2])
  };
}

const labels = readFileSync(sourcePath, "utf8")
  .split(/\r?\n/)
  .map((line, index) => parseAtlasLine(line, index + 1))
  .filter(Boolean)
  .sort((a, b) => a.x - b.x);

const output = `// Generated by generate_arcturus_labels.mjs from ${basename(sourcePath)}.
// Do not edit this file by hand.
export const ARCTURUS_ATOMIC_LABELS = ${JSON.stringify(labels, null, 2)};
`;

writeFileSync(outputPath, output, "utf8");
console.log(`Wrote ${labels.length} Arcturus labels to ${outputPath}.`);
